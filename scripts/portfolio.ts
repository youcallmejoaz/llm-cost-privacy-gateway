/**
 * npm run portfolio: checks the Upwork field limits and writes docs/UPWORK_PORTFOLIO.md
 * from docs/portfolio.fields.json, with the character count printed next to every field.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const f = JSON.parse(readFileSync('docs/portfolio.fields.json', 'utf8'));
const LIMITS = { title: 70, role: 100, description: 600 };
const errors: string[] = [];
const count = (label: string, text: string, limit: number) => {
  const n = [...text].length;
  if (n > limit) errors.push(`${label}: ${n} > ${limit}`);
  if (/[—–]/.test(text)) errors.push(`${label}: contains an em or en dash`);
  return `${n} / ${limit} characters`;
};

const titles = f.titles.map((t: string, i: number) => `${i + 1}. ${t}  \n   _(${count(`title ${i + 1}`, t, LIMITS.title)})_${i === f.recommendedTitle ? ' **Recommended.**' : ''}`);
if (f.skills.length !== 5) errors.push(`skills: need exactly 5, have ${f.skills.length}`);
const snippet = f.snippet.replace('{repo}', f.repo);

const md = `# Upwork portfolio entry

Generated by \`npm run portfolio\` from \`docs/portfolio.fields.json\`. Counts are computed, not typed.

## 1. Project title (max ${LIMITS.title})

${titles.join('\n')}

Why the recommended one: ${f.titleWhy}

## 2. Your role (max ${LIMITS.role})

> ${f.role}

_(${count('role', f.role, LIMITS.role)})_

## 3. Project description (max ${LIMITS.description})

> ${f.description}

_(${count('description', f.description, LIMITS.description)})_

The only number used (54 automated tests) comes from the real test run. It is described as a demo build on sample data, not client work.

## 4. Skills (exactly 5)

${f.skills.map((s: string) => `- ${s}`).join('\n')}

If Upwork does not offer one of these as a tag, swap only that one.

## 5. Content blocks, in this order

1. Cover image: \`docs/upwork-cover-a.png\` (1600 x 1200, 4:3). Alternative: \`docs/upwork-cover-b.png\`.
2. Video: upload \`clips/proposal_cut.mp4\`.
${f.screenshots.map((s: { file: string; caption: string }, i: number) => `${i + 3}. Screenshot: \`${s.file}\`  \n   Caption: ${s.caption}`).join('\n')}
5. Link: ${f.repo}
6. YouTube: _add the link once the video is published_

## 6. Proposal snippet

> ${snippet}

The link points at the \`main\` branch, so it works once this work is merged to \`main\`.
`;

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}
writeFileSync('docs/UPWORK_PORTFOLIO.md', md);
console.log('wrote docs/UPWORK_PORTFOLIO.md');
console.log(f.titles.map((t: string) => `title ${[...t].length}`).join(', '), `| role ${[...f.role].length} | description ${[...f.description].length}`);
